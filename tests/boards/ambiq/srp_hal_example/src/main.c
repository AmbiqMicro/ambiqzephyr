static const struct crypto_ambiq_srp_group srp_group = {
	.n = modulus,
	.g = generator,
	.modulus_bytes = SRP_MOD_BYTES,
	.hash = CRYPTO_HASH_ALGO_SHA256,
};

int main(void)
{
	const struct device *dev = SRP_DEV;
	const struct crypto_ambiq_srp_driver_api *api;
	int ret;
	bool ok_k;
	bool ok_v;

	printk("\nAmbiq CC312 SRP driver checks\n\n");

	if (!device_is_ready(dev)) {
		printk("SRP device not ready\n");
		return 0;
	}

	api = (const struct crypto_ambiq_srp_driver_api *)dev->api;

	am_hal_cc312_context_clear(g_k, sizeof(g_k));
	ret = api->derive_k(dev, &srp_group, g_k);
	ok_k = (ret == 0) && (memcmp(g_k, k_exp, sizeof(k_exp)) == 0);
	printk("SRP derive_k (RFC5054 1024-bit)          %s\n", ok_k ? "PASS" : "FAIL");

	am_hal_cc312_context_clear(g_v, sizeof(g_v));
	ret = crypto_ambiq_srp_derive_verifier(dev, &srp_group, x_val, sizeof(x_val), g_v);
	ok_v = (ret == 0) && (memcmp(g_v, v_exp, sizeof(v_exp)) == 0);
	printk("SRP derive_verifier                    %s\n", ok_v ? "PASS" : "FAIL");

	if (ok_k && ok_v) {
		printk("All driver checks passed\n");
	}

	return 0;
}
